<?php

namespace PhalconInertia;

use Phalcon\Di\Injectable;

class Routes extends Injectable
{
    const METHODS = ['GET', 'HEAD', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'];

    const DEFAULT_WHERE = '[^/]*';

    private $options = [
        'url' => null,
        'only' => [],
        'except' => [],
        'groups' => [],
        'defaults' => [],
    ];

    /**
     * @param array|\Phalcon\Config $options url, only, except, groups and defaults
     */
    public function __construct($options = [])
    {
        $options = is_object($options) && method_exists($options, 'toArray') ? $options->toArray() : (array) $options;
        $this->options = array_merge($this->options, $options);
    }

    /**
     * $only and $except take route names or groups, with * wildcards, and override the options.
     *
     * @param string|string[]|null $only
     * @param string|string[]|null $except
     * @return array
     */
    public function toArray($only = null, $except = null)
    {
        $url = rtrim($this->options['url'] !== null ? $this->options['url'] : $this->requestUrl(), '/');
        $port = parse_url($url, PHP_URL_PORT);

        return [
            'url' => $url,
            'port' => $port ? $port : null,
            'defaults' => $this->options['defaults'],
            'routes' => $this->routes($only, $except),
        ];
    }

    /**
     * @param string|string[]|null $only
     * @param string|string[]|null $except
     * @return string
     */
    public function toJson($only = null, $except = null)
    {
        $config = $this->toArray($only, $except);
        $config['defaults'] = (object) $config['defaults'];
        $config['routes'] = (object) $config['routes'];

        return json_encode($config, JSON_UNESCAPED_SLASHES | JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT);
    }

    /**
     * @param string|string[]|null $only
     * @param string|string[]|null $except
     * @param string|null $nonce
     * @param bool $withFunction Also define the global route() function
     * @return string
     */
    public function script($only = null, $except = null, $nonce = null, $withFunction = true)
    {
        $nonce = $nonce === null ? '' : ' nonce="'.htmlspecialchars($nonce, ENT_QUOTES, 'UTF-8').'"';
        $function = $withFunction ? self::routeFunction() : '';

        return '<script'.$nonce.'>const PhalconRoutes = '.$this->toJson($only, $except).';'.$function.'</script>';
    }

    /**
     * TypeScript declaration of the route names and their parameters.
     *
     * @param string|string[]|null $only
     * @param string|string[]|null $except
     * @return string
     */
    public function types($only = null, $except = null)
    {
        $list = [];
        foreach ($this->routes($only, $except) as $name => $route) {
            $parameters = [];
            foreach (isset($route['parameters']) ? $route['parameters'] : [] as $parameter) {
                $parameters[] = ['name' => $parameter, 'required' => true];
            }
            $list[] = '    '.json_encode($name).': '.json_encode($parameters, JSON_UNESCAPED_SLASHES).',';
        }

        return "/* This file is generated by phalcon-inertia, do not edit it. */\n"
            ."declare module 'phalcon-routes' {\n"
            ."  interface RouteList {\n"
            .($list ? implode("\n", $list)."\n" : '')
            ."  }\n"
            ."}\n"
            ."export {};\n";
    }

    private function routes($only = null, $except = null)
    {
        $only = $this->expand($only === null ? $this->options['only'] : (array) $only);
        $except = $this->expand($except === null ? $this->options['except'] : (array) $except);
        $base = rtrim((string) $this->url->getBaseUri(), '/');
        $routes = [];
        foreach ($this->router->getRoutes() as $route) {
            $name = (string) $route->getName();
            if ($name === '' || ($only && ! self::matches($name, $only)) || self::matches($name, $except)) {
                continue;
            }

            $placeholders = ['for' => $name];
            $positions = [];
            foreach ($route->getPaths() as $parameter => $position) {
                if (is_int($position)) {
                    $placeholders[$parameter] = '{'.$parameter.'}';
                    $positions[$parameter] = $position;
                }
            }

            $uri = preg_replace('#^([a-z][a-z0-9+.-]*:)?//[^/]*#i', '', (string) $this->url->get($placeholders));
            if ($base !== '' && strpos($uri, $base) === 0) {
                $uri = substr($uri, strlen($base));
            }
            $uri = trim($uri, '/');
            preg_match_all('/\{(\w+)\}/', $uri, $matches);

            $routes[$name] = array_filter([
                'uri' => $uri === '' ? '/' : $uri,
                'methods' => self::methods($route->getHttpMethods()),
                'domain' => self::domain($route->getHostname()),
                'parameters' => $matches[1],
                'wheres' => self::wheres((string) $route->getCompiledPattern(), $positions),
            ]);
        }

        return $routes;
    }

    private static function routeFunction()
    {
        static $function;
        if ($function === null) {
            $function = trim(file_get_contents(__DIR__.'/../js/dist/route.umd.js'));
        }

        return $function;
    }

    private function requestUrl()
    {
        return $this->request->getScheme().'://'.$this->request->getHttpHost().$this->url->getBaseUri();
    }

    private static function methods($methods)
    {
        if ($methods === null || $methods === []) {
            return self::METHODS;
        }

        return array_values(array_map('strtoupper', (array) $methods));
    }

    private static function domain($hostname)
    {
        return $hostname !== null && preg_match('/^[\w.-]+$/', $hostname) ? $hostname : null;
    }

    private static function wheres($compiled, array $positions)
    {
        $groups = self::groups($compiled);
        $wheres = [];
        foreach ($positions as $parameter => $position) {
            if (isset($groups[$position]) && $groups[$position] !== self::DEFAULT_WHERE) {
                $wheres[$parameter] = $groups[$position];
            }
        }

        return $wheres;
    }

    private static function groups($regex)
    {
        $groups = [];
        $open = [];
        $length = strlen($regex);
        for ($i = 0; $i < $length; $i++) {
            $char = $regex[$i];
            if ($char === '\\') {
                $i++;
            } elseif ($char === '[') {
                $i += $i + 1 < $length && $regex[$i + 1] === '^' ? 2 : 1;
                $i += $i < $length && $regex[$i] === ']' ? 1 : 0;
                while ($i < $length && $regex[$i] !== ']') {
                    $i += $regex[$i] === '\\' ? 2 : 1;
                }
            } elseif ($char === '(') {
                $capturing = $i + 1 >= $length || $regex[$i + 1] !== '?';
                $open[] = [$i, $capturing ? count($groups) + 1 : null];
                if ($capturing) {
                    $groups[count($groups) + 1] = null;
                }
            } elseif ($char === ')' && $open) {
                $group = array_pop($open);
                if ($group[1] !== null) {
                    $groups[$group[1]] = substr($regex, $group[0] + 1, $i - $group[0] - 1);
                }
            }
        }

        return $groups;
    }

    private function expand(array $patterns)
    {
        $expanded = [];
        foreach ($patterns as $pattern) {
            $expanded = array_merge($expanded, isset($this->options['groups'][$pattern]) ? (array) $this->options['groups'][$pattern] : [$pattern]);
        }

        return $expanded;
    }

    private static function matches($name, array $patterns)
    {
        foreach ($patterns as $pattern) {
            if (fnmatch($pattern, $name)) {
                return true;
            }
        }

        return false;
    }
}
